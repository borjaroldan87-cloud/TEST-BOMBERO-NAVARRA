function openTopicStats(
  topicId,
  automatic=false
){
  const topic=
    topicCatalog.find(item=>
      Number(item.topicId)===
      Number(topicId)
    );

  if(!topic) return;

  statsFocusTopicId=
    Number(topicId);

  $("topicDetailTitle").textContent=
    `Desglose · ${topic.topic}`;

  renderTopicDetail(
    Number(topicId)
  );

  const panel=
    $("topicDetailPanel");

  if(panel){
    panel.open=true;

    if(!automatic){
      panel.scrollIntoView({
        behavior:"smooth",
        block:"start"
      });
    }
  }
}

